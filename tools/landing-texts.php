$link = static function ( string $slug, string $label ): string {
	$term = get_term_by( 'slug', $slug, 'product_cat' );
	if ( ! $term ) {
		return $label;
	}

	$url = get_term_link( $term );
	if ( is_wp_error( $url ) ) {
		return $label;
	}

	$path = (string) wp_parse_url( $url, PHP_URL_PATH );

	return '<a href="' . esc_url( $path ) . '">' . $label . '</a>';
};

